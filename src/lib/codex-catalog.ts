import * as cp from 'child_process';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import { parseFxEnv } from './env.js';

type Entry = Record<string, unknown>;

export interface CatalogResult {
  catalog: { fx_generated: string; models: Entry[] };
  cloned: string[];
  refused: { slug: string; reason: string }[];
}

export const CATALOG_MARKER = 'generated by fx (lib/codex-catalog.js); fx-setup rewrites this file';

const FALLBACK_PATH = path.join(__dirname, '..', 'codex', 'fallback-model-info.json');

export function loadFallback(): Entry {
  return JSON.parse(fs.readFileSync(FALLBACK_PATH, 'utf8')); // ts-gate-ok: the file is fx-shipped JSON
}

function instructionTexts(e: Entry): string[] {
  const mm = e.model_messages as { instructions_template?: unknown } | null | undefined;
  return [e.base_instructions, mm?.instructions_template].filter((t): t is string => typeof t === 'string');
}

export function buildCatalog({ entries, slugs, fallback }: { entries: unknown[]; slugs: string[]; fallback?: Entry }): CatalogResult {
  if (slugs.length === 0) throw new Error('no slugs: Codex rejects an empty model catalog');
  const bySlug = new Map<string, Entry>();
  for (const e of entries as Entry[]) bySlug.set(String(e.slug), e);
  const result: CatalogResult = { catalog: { fx_generated: CATALOG_MARKER, models: [] }, cloned: [], refused: [] };
  for (const slug of new Set(slugs)) {
    const own = bySlug.get(slug);
    const base = own ?? { ...(fallback ?? loadFallback()), slug, display_name: slug };
    if (own) {
      const reason = own.include_skills_usage_instructions === true
        ? 'already has skill usage instructions'
        : instructionTexts(own).some((t) => /^# Skills$/m.test(t))
          ? 'its instructions carry their own # Skills section'
          : null;
      if (reason) {
        result.refused.push({ slug, reason });
        continue;
      }
    } else {
      result.cloned.push(slug);
    }
    result.catalog.models.push({ ...base, include_skills_usage_instructions: true, apply_patch_tool_type: 'freeform' });
  }
  return result;
}

export const PROFILE_MARKER = '# generated by fx (lib/codex-catalog.js): fx-setup rewrites this file; edit your own config.toml instead';

export interface SetupReport {
  provider: string | null;
  slugs: string[];
  profile: string | null;
  command: string | null;
  written: string[];
  kept: string[];
  cloned: string[];
  refused: { slug: string; reason: string }[];
  skipped: string | null;
  // fx profiles other than this run's, still in place; fx never removes them.
  left: string[];
}

// Only the top-level string keys model and model_provider; tables start at the first "[" line.
function readConfig(file: string): { model: string | null; provider: string | null } {
  const out = { model: null as string | null, provider: null as string | null };
  let text: string;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return out;
    throw e;
  }
  for (const line of text.split('\n')) {
    if (/^\s*\[/.test(line)) break;
    const m = /^\s*(model|model_provider)\s*=\s*(?:"([^"]*)"|'([^']*)')/.exec(line);
    if (m) out[m[1] === 'model' ? 'model' : 'provider'] = (m[2] ?? m[3]) as string;
  }
  return out;
}

// 120 s: a provider refresh answers in seconds, so two minutes cuts off a hang without failing a slow network.
function defaultListModels(): unknown[] {
  const out = cp.execFileSync('codex', ['debug', 'models'], { encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, timeout: 120_000 });
  return JSON.parse(out).models; // ts-gate-ok: output of codex debug models, shape trusted as Codex ships it
}

function isRegular(file: string): boolean | null {
  try {
    return fs.lstatSync(file).isFile();
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw e;
  }
}

const ownsProfile = (file: string): boolean =>
  fs.readFileSync(file, 'utf8').split('\n', 1)[0] === PROFILE_MARKER;

// fx profiles an earlier run wrote, still in place after the model or provider changed.
function leftProfiles(home: string): string[] {
  let names: string[];
  try {
    names = fs.readdirSync(home);
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw e;
  }
  return names.filter((n) => /^fx-.*\.config\.toml$/.test(n)).sort()
    .map((n) => path.join(home, n)).filter((f) => isRegular(f) === true && ownsProfile(f));
}

function ownsCatalog(file: string): boolean {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8')).fx_generated === CATALOG_MARKER; // ts-gate-ok: parse failure is caught above and means not fx-owned
  } catch {
    return false;
  }
}

// Same-directory temp file then rename: a cut-short write never leaves a torn file, and the new file is 0600 even over an older mode.
function writeAtomic(file: string, text: string): void {
  const tmp = `${file}.${process.pid}.tmp`;
  try {
    fs.writeFileSync(tmp, text, { mode: 0o600, flag: 'wx' });
    fs.renameSync(tmp, file);
  } catch (e) {
    fs.rmSync(tmp, { force: true });
    throw e;
  }
}

export function setupCatalog({ codexHome, slugs: named = [], listModels = defaultListModels }: { codexHome?: string; slugs?: string[]; listModels?: () => unknown[] } = {}): SetupReport {
  const home = codexHome || parseFxEnv(process.env).codexHome || path.join(os.homedir(), '.codex');
  const cfg = readConfig(path.join(home, 'config.toml'));
  const thirdParty = cfg.provider !== null && cfg.provider !== 'openai';
  const slugs = [...new Set([...(thirdParty && cfg.model ? [cfg.model] : []), ...named])];
  const report: SetupReport = { provider: cfg.provider, slugs, profile: null, command: null, written: [], kept: [], cloned: [], refused: [], skipped: null, left: [] };
  if (slugs.length === 0) {
    report.skipped = 'no third-party model in config.toml and no slug named';
    report.left = leftProfiles(home);
    return report;
  }
  const provider = thirdParty ? (cfg.provider as string) : 'custom';
  if (!/^[A-Za-z0-9_-]+$/.test(provider)) throw new Error(`provider name not usable in a file name: ${provider}`);

  const name = `fx-${provider}`;
  const catalogFile = path.join(home, `${name}.catalog.json`);
  const profileFile = path.join(home, `${name}.config.toml`);
  report.left = leftProfiles(home).filter((f) => f !== profileFile);
  for (const [file, owns] of [[catalogFile, ownsCatalog], [profileFile, ownsProfile]] as const) {
    const regular = isRegular(file);
    if (regular !== null && !(regular && owns(file))) report.kept.push(file);
  }
  if (report.kept.length > 0) return report;

  const built = buildCatalog({ entries: listModels(), slugs });
  report.cloned = built.cloned;
  report.refused = built.refused;
  if (built.catalog.models.length === 0) return report;

  fs.mkdirSync(home, { recursive: true });
  writeAtomic(catalogFile, JSON.stringify(built.catalog, null, 1) + '\n');
  writeAtomic(profileFile, `${PROFILE_MARKER}\nmodel_catalog_json = ${JSON.stringify(path.resolve(catalogFile))}\n`);
  report.written = [catalogFile, profileFile];
  report.profile = name;
  report.command = `codex --profile ${name}`;
  return report;
}

if (require.main === module) {
  const [cmd, ...slugs] = process.argv.slice(2);
  if (cmd !== 'setup') {
    process.stderr.write('usage: node lib/codex-catalog.js setup [slug...]\n');
    process.exit(2);
  }
  try {
    const report = setupCatalog({ slugs });
    process.stdout.write(JSON.stringify(report) + '\n');
    process.exit(report.profile ? 0 : 3);
  } catch (e) {
    process.stderr.write(`${(e as Error).message}\n`);
    process.exit(1);
  }
}
