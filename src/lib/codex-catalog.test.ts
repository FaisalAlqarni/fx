// Seam: buildCatalog, asserted on the returned document (task 01).
import * as assert from 'assert';
import * as fs from 'fs';
import * as path from 'path';

const { buildCatalog, loadFallback, CATALOG_MARKER } = require('./codex-catalog');

const haiku = {
  slug: 'anthropic/claude-haiku-4.5',
  display_name: 'Claude Haiku 4.5',
  context_window: 200000,
  max_context_window: 200000,
  include_skills_usage_instructions: false,
  apply_patch_tool_type: null,
  base_instructions: 'BASE',
  model_messages: { instructions_template: 'BASE' },
  shell_type: 'unified_exec',
  visibility: 'list',
};

// Flags flipped, everything else kept; the input is left alone.
{
  const r = buildCatalog({ entries: [haiku], slugs: ['anthropic/claude-haiku-4.5'] });
  assert.deepStrictEqual(r.catalog.models, [
    { ...haiku, include_skills_usage_instructions: true, apply_patch_tool_type: 'freeform' },
  ]);
  assert.strictEqual(r.catalog.models[0].context_window, 200000);
  assert.deepStrictEqual(r.cloned, []);
  assert.deepStrictEqual(r.refused, []);
  assert.strictEqual(r.catalog.fx_generated, CATALOG_MARKER);
  assert.strictEqual(haiku.include_skills_usage_instructions, false);
  assert.strictEqual(haiku.apply_patch_tool_type, null);
}

assert.strictEqual(CATALOG_MARKER, 'generated by fx (lib/codex-catalog.js); fx-setup rewrites this file');

// An unknown slug gets a clone of Codex's fallback entry.
{
  const r = buildCatalog({ entries: [], slugs: ['acme/m1'] });
  assert.strictEqual(r.catalog.models.length, 1);
  const m = r.catalog.models[0];
  assert.strictEqual(m.slug, 'acme/m1');
  assert.strictEqual(m.display_name, 'acme/m1');
  assert.strictEqual(m.context_window, 272000);
  assert.strictEqual(m.max_context_window, 272000);
  assert.strictEqual(m.include_skills_usage_instructions, true);
  assert.strictEqual(m.apply_patch_tool_type, 'freeform');
  assert.strictEqual(m.model_messages.instructions_template, loadFallback().model_messages.instructions_template);
  assert.deepStrictEqual(r.cloned, ['acme/m1']);
}

// An entry that already has the skills flag is refused.
{
  const r = buildCatalog({ entries: [{ slug: 'gpt-5.5', include_skills_usage_instructions: true }], slugs: ['gpt-5.5'] });
  assert.deepStrictEqual(r.catalog.models, []);
  assert.deepStrictEqual(r.refused, [{ slug: 'gpt-5.5', reason: 'already has skill usage instructions' }]);
}

// An entry whose instructions carry a # Skills section is refused, wherever the text sits.
{
  const text = 'You are Codex.\n\n# Skills\n\nUse skills when...';
  const reason = 'its instructions carry their own # Skills section';
  const viaTemplate = { slug: 'gpt-6.1-sol', include_skills_usage_instructions: false, model_messages: { instructions_template: text } };
  const viaBase = { slug: 'gpt-6.1-sol', include_skills_usage_instructions: false, base_instructions: text };
  for (const e of [viaTemplate, viaBase]) {
    const r = buildCatalog({ entries: [e], slugs: ['gpt-6.1-sol'] });
    assert.deepStrictEqual(r.refused, [{ slug: 'gpt-6.1-sol', reason }]);
    assert.deepStrictEqual(r.catalog.models, []);
  }
}

// Duplicate slugs collapse, because Codex rejects duplicates in a catalog.
{
  const r = buildCatalog({ entries: [], slugs: ['acme/m1', 'acme/m1'] });
  assert.strictEqual(r.catalog.models.length, 1);
  assert.deepStrictEqual(r.cloned, ['acme/m1']);
}

// An empty slug list is an error, because Codex rejects an empty catalog.
assert.throws(
  () => buildCatalog({ entries: [], slugs: [] }),
  (e: unknown) => e instanceof Error && e.message === 'no slugs: Codex rejects an empty model catalog',
);

// The vendored fallback is Codex's own, with no literal dash in the shipped bytes.
{
  const f = loadFallback();
  assert.strictEqual(f.include_skills_usage_instructions, false);
  assert.ok(f.apply_patch_tool_type === undefined || f.apply_patch_tool_type === null);
  assert.strictEqual(f.context_window, 272000);
  assert.strictEqual(f.shell_type, 'unified_exec');
  assert.ok(f.model_messages.instructions_template.startsWith('You are a coding agent running in the Codex CLI'));
  const raw = fs.readFileSync(path.join(__dirname, '..', 'codex', 'fallback-model-info.json'), 'utf8');
  assert.ok(!raw.includes('—') && !raw.includes('–'));
}

console.log('codex-catalog: ok');
